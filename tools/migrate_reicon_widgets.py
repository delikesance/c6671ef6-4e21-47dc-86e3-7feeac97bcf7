"""Replace app-owned Flutter Icon widgets with the Reicon SVG bridge.

The source may still pass Material IconData to typed APIs; AppIcon resolves
those values using the complete map generated by generate_reicon_material_map.py.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
LIB = ROOT / 'packages/app/lib'
IMPORT = "import 'package:bot_creator/core/widgets/app_icon.dart';"
ICON = re.compile(r'\bIcon\(')


def add_import(path: pathlib.Path) -> None:
    source = path.read_text()
    if IMPORT in source or path.name == 'app_icon.dart':
        return
    imports = list(re.finditer(r'^import .*?;\s*$', source, re.M))
    if not imports:
        raise SystemExit(f'Cannot add AppIcon import to {path}')
    last = imports[-1]
    source = source[:last.end()] + '\n' + IMPORT + source[last.end():]
    path.write_text(source)


def main() -> None:
    edited = 0
    calls = 0
    parents: set[pathlib.Path] = set()
    for path in LIB.rglob('*.dart'):
        if path.name in {'app_icon.dart', 'reicon_material_map.dart'}:
            continue
        source = path.read_text()
        changed, count = ICON.subn('AppIcon.fromMaterial(', source)
        if not count:
            continue
        path.write_text(changed)
        edited += 1
        calls += count
        part = re.search(r"^part of '([^']+)';", source, re.M)
        parents.add(path.parent / part.group(1) if part else path)
    for parent in parents:
        add_import(parent)
    print(f'Migrated {calls} Icon widgets in {edited} files; imported {len(parents)} libraries')


if __name__ == '__main__':
    main()
