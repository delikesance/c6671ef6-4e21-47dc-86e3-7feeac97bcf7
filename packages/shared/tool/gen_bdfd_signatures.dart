// Regenerates lib/engine/bdfd/validation/bdfd_signatures.g.dart from the real
// native registry (`BdfdEngine.validation()`):
//
//   dart run tool/gen_bdfd_signatures.dart
//
// `test/bdfd_validation_table_test.dart` fails whenever the committed table
// differs from the registry, so run this after adding or changing a function.
import 'dart:io';

import 'package:bot_creator_shared/engine/bdfd/engine.dart';
import 'package:bot_creator_shared/engine/bdfd/runtime.dart';

const outputPath = 'lib/engine/bdfd/validation/bdfd_signatures.g.dart';

String renderBdfdSignatureTable() {
  final core = BdfdRuntime().functionSignatures.keys.toSet();
  final all = BdfdEngine.validation().functionSignatures;
  final names = all.keys.where((name) => !core.contains(name)).toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_bdfd_signatures.dart. Do not edit.')
    ..writeln('//')
    ..writeln(
      '// Argument signatures of the supplied (non-core) native BDFD functions,',
    )
    ..writeln('// so validation needs no service or nyxx dependency.')
    ..writeln()
    ..writeln("import '../runtime.dart' show BdfdFunctionSignature;")
    ..writeln()
    ..writeln(
      'const bdfdSuppliedFunctionSignatures = <String, BdfdFunctionSignature>{',
    );
  for (final name in names) {
    final s = all[name]!;
    final counts = s.allowedArgumentCounts;
    final extra = counts == null
        ? ''
        : ', {${(counts.toList()..sort()).join(', ')}}';
    out.writeln(
      "  '$name': BdfdFunctionSignature(${s.minArguments}, ${s.maxArguments}$extra),",
    );
  }
  out.writeln('};');
  return out.toString();
}

void main() {
  File(outputPath).writeAsStringSync(renderBdfdSignatureTable());
  stdout.writeln('Wrote $outputPath');
}
